#!/usr/bin/env python3
"""Generate every derived artefact of the plan from data/curriculum.json.

    python3 scripts/build.py          # (re)generate files in place
    python3 scripts/build.py --check  # validate + fail if any generated file is stale (CI)

Generated (never edit by hand):
    assets/curriculum.data.js        data bundle used by the tracker (works over file://)
    curriculum/README.md             phase index
    curriculum/phase-N-<slug>.md     one document per phase, every day and problem
    PROBLEMS.md                      every problem in the plan, with day / pattern / difficulty
    PATTERNS.md                      pattern index with problem counts
    patterns/<id>.md                 only the blocks between <!-- generated:... --> markers
    README.md                        only the blocks between <!-- generated:... --> markers

Standard library only. Output is deterministic so `--check` is a plain byte comparison.
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter, OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "curriculum.json"
REPO = "https://github.com/RANJITHROSAN17/dsa-mastery-plan-2026"
SITE = "https://ranjithrosan17.github.io/dsa-mastery-plan-2026/"
DIFF_BADGE = {"Easy": "🟢 Easy", "Medium": "🟡 Medium", "Hard": "🔴 Hard"}
KIND_LABEL = {"learn": "Learn", "review": "Review", "mock": "Mock"}
NOTICE = "<!-- GENERATED by scripts/build.py from data/curriculum.json — do not edit by hand. -->"


# ----------------------------------------------------------------------------- helpers
def slugify(text: str) -> str:
    text = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return re.sub(r"-{2,}", "-", text)


def all_days(data: dict):
    for phase in data["phases"]:
        for week in phase["weeks"]:
            for day in week["days"]:
                yield phase, week, day


def problem_cell(p: dict, with_video: bool = True) -> str:
    cell = f"[{p['id']}. {p['title']}]({p['url']})"
    if p.get("core"):
        cell += " ⭐"
    if p.get("repeat"):
        cell += " 🔁"
    if with_video and p.get("video"):
        cell += f" [▶]({p['video']})"
    return cell


def md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def replace_block(text: str, name: str, body: str) -> str:
    start, end = f"<!-- generated:{name}:start -->", f"<!-- generated:{name}:end -->"
    if start not in text or end not in text:
        raise SystemExit(f"missing markers for block '{name}'")
    pre, rest = text.split(start, 1)
    _, post = rest.split(end, 1)
    return f"{pre}{start}\n{body.rstrip()}\n{end}{post}"


# ----------------------------------------------------------------------------- validation
def validate(data: dict) -> list[str]:
    errors: list[str] = []
    patterns = data["patterns"]
    days = [d for _, _, d in all_days(data)]
    if [d["day"] for d in days] != list(range(1, data["meta"]["days"] + 1)):
        errors.append("days are not contiguous 1..N")
    first_seen: dict[str, int] = {}
    for phase, week, d in days_with_context(data):
        ctx = f"day {d['day']}"
        if d["phase"] != phase["id"]:
            errors.append(f"{ctx}: phase mismatch")
        if d["week"] != week["week"]:
            errors.append(f"{ctx}: week mismatch")
        if d["kind"] not in KIND_LABEL:
            errors.append(f"{ctx}: unknown kind {d['kind']}")
        if d["pattern"] not in patterns:
            errors.append(f"{ctx}: unknown pattern {d['pattern']}")
        if not d["goal"].strip():
            errors.append(f"{ctx}: empty goal")
        for p in d["problems"]:
            for key in ("id", "slug", "title", "difficulty", "url"):
                if key not in p:
                    errors.append(f"{ctx}: problem missing {key}: {p}")
            if p.get("difficulty") not in DIFF_BADGE:
                errors.append(f"{ctx}: bad difficulty for {p.get('slug')}")
            if p.get("url") != f"https://leetcode.com/problems/{p.get('slug')}/":
                errors.append(f"{ctx}: url/slug mismatch for {p.get('slug')}")
            if p["slug"] in first_seen and not p.get("repeat"):
                errors.append(f"{ctx}: {p['slug']} already used on day {first_seen[p['slug']]} but not flagged repeat")
            if p.get("repeat") and p["slug"] not in first_seen:
                errors.append(f"{ctx}: {p['slug']} flagged repeat but never seen before")
            first_seen.setdefault(p["slug"], d["day"])
            if p.get("video") and not p["video"].startswith("https://www.youtube.com/watch?v="):
                errors.append(f"{ctx}: bad video url for {p['slug']}")
    for phase in data["phases"]:
        n = sum(len(w["days"]) for w in phase["weeks"])
        if n != 30:
            errors.append(f"phase {phase['id']} has {n} days, expected 30")
        if [w["week"] for w in phase["weeks"]] != [1, 2, 3, 4, 5]:
            errors.append(f"phase {phase['id']} weeks are not 1..5")
    for pid, pat in patterns.items():
        for key in ("name", "phase", "summary", "cues", "resources"):
            if key not in pat:
                errors.append(f"pattern {pid}: missing {key}")
        for r in pat.get("resources", []):
            if not r.get("url", "").startswith("https://"):
                errors.append(f"pattern {pid}: bad resource url {r}")
    used = {d["pattern"] for d in days}
    for pid in patterns:
        if pid not in used:
            errors.append(f"pattern {pid} is never scheduled")
    return errors


def days_with_context(data: dict):
    return list(all_days(data))


# ----------------------------------------------------------------------------- stats
def stats(data: dict) -> dict:
    uniq: "OrderedDict[str, dict]" = OrderedDict()
    for _, _, d in all_days(data):
        for p in d["problems"]:
            if p["slug"] not in uniq:
                uniq[p["slug"]] = {**p, "day": d["day"], "pattern": d["pattern"], "phase": d["phase"]}
    diff = Counter(p["difficulty"] for p in uniq.values())
    return {
        "unique": len(uniq),
        "slots": sum(len(d["problems"]) for _, _, d in all_days(data)),
        "core": sum(1 for p in uniq.values() if p.get("core")),
        "videos": sum(1 for p in uniq.values() if p.get("video")),
        "easy": diff["Easy"],
        "medium": diff["Medium"],
        "hard": diff["Hard"],
        "patterns": len(data["patterns"]),
        "problems": uniq,
    }


# ----------------------------------------------------------------------------- renderers
def render_data_js(data: dict) -> str:
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))  # keep curriculum order (no sort_keys)
    return (
        "/* GENERATED by scripts/build.py from data/curriculum.json — do not edit by hand. */\n"
        f"window.DSA_DATA = {payload};\n"
    )


def phase_filename(phase: dict) -> str:
    return f"phase-{phase['id']}-{slugify(phase['title'])}.md"


def render_phase(data: dict, phase: dict) -> str:
    pats = data["patterns"]
    out = [NOTICE, "", f"# Phase {phase['id']} — {phase['title']}", "",
           f"**{phase['span']}** · {phase['summary']}", "",
           f"[← Curriculum index](README.md) · [Live tracker]({SITE}#/day/{phase['weeks'][0]['days'][0]['day']}) · "
           f"[All problems](../PROBLEMS.md) · [Pattern playbooks](../PATTERNS.md)", ""]
    used = Counter()
    for w in phase["weeks"]:
        for d in w["days"]:
            used[d["pattern"]] += 1
    out += ["## Patterns in this phase", ""]
    out += ["| Pattern | Days | Playbook |", "|---|---:|---|"]
    for pid, n in used.most_common():
        out.append(f"| {pats[pid]['name']} | {n} | [patterns/{pid}.md](../patterns/{pid}.md) |")
    out.append("")
    out += ["## Week overview", "", "| Week | Days | Focus |", "|---|---|---|"]
    for w in phase["weeks"]:
        out.append(f"| {w['week']} | {w['days_span']} | {w['title']} |")
    out.append("")
    for w in phase["weeks"]:
        out += [f"## Week {w['week']} · {w['title']} (days {w['days_span']})", ""]
        for d in w["days"]:
            kind = KIND_LABEL[d["kind"]]
            out += [f"### Day {d['day']} — {md_escape(d['topic'])}", "",
                    f"`{kind}` · Pattern: [{pats[d['pattern']]['name']}](../patterns/{d['pattern']}.md)", "",
                    f"**Goal:** {d['goal']}", ""]
            if d["learn"]:
                out += ["**Learn / do:**", ""] + [f"- {item}" for item in d["learn"]] + [""]
            if d["problems"]:
                out += ["| Problem | Difficulty |", "|---|---|"]
                for p in d["problems"]:
                    out.append(f"| {problem_cell(p)} | {DIFF_BADGE[p['difficulty']]} |")
                out.append("")
    out += ["---", "", "Legend: ⭐ core (fast-track) problem · 🔁 deliberate repeat · ▶ verified video walkthrough.", ""]
    return "\n".join(out)


def render_curriculum_index(data: dict, st: dict) -> str:
    out = [NOTICE, "", "# Curriculum — 150 days, 5 phases", "",
           f"{st['unique']} unique LeetCode problems ({st['easy']} easy · {st['medium']} medium · {st['hard']} hard), "
           f"{st['patterns']} patterns, {st['core']} ⭐ core problems. Every day lists a goal, what to learn and the problems to solve.", "",
           "| Phase | Days | Theme | Problems |", "|---|---|---|---:|"]
    for ph in data["phases"]:
        n = sum(len(d["problems"]) for w in ph["weeks"] for d in w["days"])
        out.append(f"| [{ph['id']}. {ph['title']}]({phase_filename(ph)}) | {ph['span'].replace('Days ', '')} | {ph['summary']} | {n} |")
    out += ["", "Prefer clicking? The same data drives the [live tracker](" + SITE + ").", ""]
    return "\n".join(out)


def render_problems(data: dict, st: dict) -> str:
    pats = data["patterns"]
    out = [NOTICE, "", "# All problems", "",
           f"{st['unique']} unique problems across 150 days — {st['easy']} 🟢 easy, {st['medium']} 🟡 medium, {st['hard']} 🔴 hard. "
           f"⭐ marks the {st['core']} core problems (the fast track). ▶ marks a verified video walkthrough. Day links open the tracker.", "",
           "Sorted by the day each problem is first assigned. Use your browser's find (Ctrl/Cmd+F) to search by name or LeetCode number.", "",
           "| # | Problem | Difficulty | Pattern | Day |", "|---:|---|---|---|---:|"]
    for p in st["problems"].values():
        out.append(f"| {p['id']} | {problem_cell(p)} | {DIFF_BADGE[p['difficulty']]} | "
                   f"[{pats[p['pattern']]['name']}](patterns/{p['pattern']}.md) | [{p['day']}]({SITE}#/day/{p['day']}) |")
    out += ["", "## By difficulty", ""]
    for diff in ("Easy", "Medium", "Hard"):
        names = [f"[{p['id']}]({p['url']} \"{p['title']}\")" for p in st["problems"].values() if p["difficulty"] == diff]
        out += [f"**{DIFF_BADGE[diff]} ({len(names)})** — " + " ".join(names), ""]
    return "\n".join(out)


def render_patterns_index(data: dict, st: dict) -> str:
    pats = data["patterns"]
    per_pattern = Counter()
    days_per_pattern: dict[str, list[int]] = {}
    for _, _, d in all_days(data):
        days_per_pattern.setdefault(d["pattern"], []).append(d["day"])
    for p in st["problems"].values():
        per_pattern[p["pattern"]] += 1
    out = [NOTICE, "", "# Pattern playbooks", "",
           f"{len(pats)} patterns cover every problem in the plan. Each playbook explains when the pattern applies, "
           "the cues that give it away, a reusable template, the usual pitfalls and the problems from the plan that use it.", "",
           "| # | Pattern | Phase | Days | Problems | Recognise it when… |", "|---:|---|---:|---|---:|---|"]
    for i, (pid, pat) in enumerate(pats.items(), 1):
        days = days_per_pattern.get(pid, [])
        span = f"{days[0]}–{days[-1]}" if days else "—"
        out.append(f"| {i} | [{pat['name']}](patterns/{pid}.md) | {pat['phase']} | {span} ({len(days)}) | {per_pattern[pid]} | {md_escape(pat['cues'])} |")
    out += ["", "Problem counts are unique problems first assigned under that pattern; review days reuse earlier patterns.", ""]
    return "\n".join(out)


PATTERN_STUB = """# {name}

> Phase {phase} · {summary}

## When to use it

{cues}

## Recognise it

- _(cue)_

## Template

```python
# TODO
```

## Pitfalls

- _(pitfall)_

## Problems in this plan

<!-- generated:problems:start -->
<!-- generated:problems:end -->

## Resources

<!-- generated:resources:start -->
<!-- generated:resources:end -->
"""


def pattern_blocks(data: dict, st: dict, pid: str) -> tuple[str, str]:
    rows = ["| Day | Problem | Difficulty |", "|---:|---|---|"]
    for p in st["problems"].values():
        if p["pattern"] == pid:
            rows.append(f"| [{p['day']}]({SITE}#/day/{p['day']}) | {problem_cell(p)} | {DIFF_BADGE[p['difficulty']]} |")
    if len(rows) == 2:
        rows = ["_No problems are first assigned under this pattern; it is practised on review days._"]
    res = [f"- [{r['title']}]({r['url']})" for r in data["patterns"][pid]["resources"]]
    res = res or ["_None yet — contributions welcome._"]
    return "\n".join(rows), "\n".join(res)


def render_pattern_doc(data: dict, st: dict, pid: str, existing: str | None) -> str:
    pat = data["patterns"][pid]
    text = existing if existing is not None else PATTERN_STUB.format(
        name=pat["name"], phase=pat["phase"], summary=pat["summary"], cues=pat["cues"])
    problems, resources = pattern_blocks(data, st, pid)
    text = replace_block(text, "problems", problems)
    text = replace_block(text, "resources", resources)
    return text


def readme_blocks(data: dict, st: dict) -> dict[str, str]:
    phase_rows = ["| Phase | Days | What you learn | Problems | Docs |", "|---|---|---|---:|---|"]
    for ph in data["phases"]:
        n = sum(len(d["problems"]) for w in ph["weeks"] for d in w["days"])
        phase_rows.append(f"| **{ph['id']}. {ph['title']}** | {ph['span'].replace('Days ', '')} | {ph['summary']} | {n} | "
                          f"[open](curriculum/{phase_filename(ph)}) |")
    pat_rows = ["| Phase | Patterns |", "|---|---|"]
    for ph in data["phases"]:
        names = [f"[{p['name']}](patterns/{pid}.md)" for pid, p in data["patterns"].items() if p["phase"] == ph["id"]]
        pat_rows.append(f"| {ph['id']}. {ph['title']} | {' · '.join(names)} |")
    numbers = (f"**{st['unique']}** unique LeetCode problems (all free) · **{st['easy']}** easy / **{st['medium']}** medium / "
               f"**{st['hard']}** hard · **{st['patterns']}** patterns · **{st['core']}** ⭐ core problems · "
               f"**{st['videos']}** ▶ verified video walkthroughs · dataset v{data['meta']['version']}, updated {data['meta']['updated']}")
    badges = [
        f'  <a href="{SITE}"><img alt="Live tracker" src="https://img.shields.io/badge/live-tracker-2563eb?logo=githubpages&logoColor=white"></a>',
        f'  <a href="{REPO}/actions/workflows/ci.yml"><img alt="CI" src="{REPO}/actions/workflows/ci.yml/badge.svg"></a>',
        f'  <a href="PROBLEMS.md"><img alt="Problems" src="https://img.shields.io/badge/problems-{st["unique"]}%20free-16a34a"></a>',
        f'  <a href="PATTERNS.md"><img alt="Patterns" src="https://img.shields.io/badge/patterns-{st["patterns"]}-7c3aed"></a>',
        '  <a href="LICENSE"><img alt="License: MIT" src="https://img.shields.io/badge/license-MIT-black"></a>',
        '  <a href="CONTRIBUTING.md"><img alt="PRs welcome" src="https://img.shields.io/badge/PRs-welcome-d97706"></a>',
    ]
    sample_day = next(d for _, _, d in all_days(data) if d["day"] == 12)
    sample_phase = next(ph for ph in data["phases"] if ph["id"] == sample_day["phase"])
    sample = [f"> **Day {sample_day['day']} — {sample_day['topic']}** · Phase {sample_phase['id']} · {data['patterns'][sample_day['pattern']]['name']}", ">",
              f"> **Goal:** {sample_day['goal']}", ">", "> | Problem | Difficulty |", "> |---|---|"]
    sample += [f"> | {problem_cell(p, with_video=False)} | {DIFF_BADGE[p['difficulty']]} |" for p in sample_day["problems"]]
    return {"phases": "\n".join(phase_rows), "patterns": "\n".join(pat_rows), "numbers": numbers,
            "badges": "\n".join(badges), "sample": "\n".join(sample)}


# ----------------------------------------------------------------------------- main
def build(check: bool) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    errors = validate(data)
    if errors:
        print("curriculum.json is invalid:\n  " + "\n  ".join(errors))
        return 1
    st = stats(data)
    outputs: dict[Path, str] = {}
    outputs[ROOT / "assets" / "curriculum.data.js"] = render_data_js(data)
    outputs[ROOT / "curriculum" / "README.md"] = render_curriculum_index(data, st)
    for ph in data["phases"]:
        outputs[ROOT / "curriculum" / phase_filename(ph)] = render_phase(data, ph)
    outputs[ROOT / "PROBLEMS.md"] = render_problems(data, st)
    outputs[ROOT / "PATTERNS.md"] = render_patterns_index(data, st)
    for pid in data["patterns"]:
        path = ROOT / "patterns" / f"{pid}.md"
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        outputs[path] = render_pattern_doc(data, st, pid, existing)
    readme = ROOT / "README.md"
    if readme.exists():
        text = readme.read_text(encoding="utf-8")
        for name, body in readme_blocks(data, st).items():
            text = replace_block(text, name, body)
        outputs[readme] = text

    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if check:
        if stale:
            print("Generated files are out of date (run `python3 scripts/build.py`):\n  " + "\n  ".join(map(str, stale)))
            return 1
        print(f"OK — {len(outputs)} generated files are up to date; "
              f"{st['unique']} problems, {st['patterns']} patterns, {data['meta']['days']} days.")
        return 0
    print(f"Wrote {len(stale)} file(s) ({len(outputs)} generated in total). "
          f"{st['unique']} unique problems · {st['slots']} slots · {st['core']} core · "
          f"E/M/H {st['easy']}/{st['medium']}/{st['hard']}.")
    return 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv[1:]))
